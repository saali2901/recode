import fs from 'node:fs/promises';
import path from 'node:path';
import { assetPath } from '../../infrastructure/filesystem/assets.js';
import {
  pathExists,
  readJsonIfExists,
  writeFileAtomic,
  writeJsonAtomic,
} from '../../infrastructure/filesystem/files.js';
import { sanitizeIdentifier } from '../../infrastructure/filesystem/paths.js';
import { z } from 'zod';
import type { FunctionInfo } from '../../decompiler/interfaces/schemas.js';
import type {
  GeneratedFileMap,
  GenerationInput,
  GenerationReport,
  TargetLanguage,
} from '../interfaces/target-language.js';
import type { FunctionResult } from '../interfaces/results.js';

const GENERATED_MANIFEST = '.recode-generated.json';
const GeneratedManifestSchema = z.object({
  files: z.array(z.string()),
  fileMap: z.object({
    files: z.record(z.string(), z.string()),
    headerLines: z.record(z.string(), z.string()),
  }),
});

export function templateDirectory(): string {
  return assetPath('templates', 'c-project');
}

/** Task id used for a function: stable across runs and derived from its address. */
export function functionTaskId(address: string): string {
  return `fn_${address.slice(2).padStart(8, '0')}`;
}

function commentSafe(text: string): string {
  return text.replace(/\*\//g, '* /').replace(/\r?\n/g, ' ');
}

export function terminated(prototype: string): string {
  const trimmed = prototype.trim();
  return trimmed.endsWith(';') ? trimmed : `${trimmed};`;
}

/** Generates a CMake-based C project from accepted agent results. */
export class CTargetLanguage implements TargetLanguage {
  readonly id = 'c';

  async generateProject(input: GenerationInput): Promise<GenerationReport> {
    const { project, binary } = input;
    const root = project.sourceDir(binary.id);
    const previous = await readJsonIfExists(
      path.join(root, GENERATED_MANIFEST),
      GeneratedManifestSchema,
    );
    await fs.mkdir(path.join(root, 'src'), { recursive: true });
    await fs.mkdir(path.join(root, 'include'), { recursive: true });

    const written = new Set<string>();
    const fileMap: GeneratedFileMap = { files: {}, headerLines: {} };
    const emit = async (relative: string, content: string, taskId?: string): Promise<void> => {
      // Unchanged files keep their modification time, so Ninja only recompiles what really changed.
      const existing = await fs.readFile(path.join(root, relative), 'utf8').catch(() => undefined);
      if (existing !== content) await writeFileAtomic(path.join(root, relative), content);
      written.add(relative);
      if (taskId) fileMap.files[`source/${binary.id}/${relative}`] = taskId;
    };

    const usedNames = new Map<string, string>();
    const reconstructed: Array<{ info: FunctionInfo; result: FunctionResult; file: string }> = [];
    const unreconstructed: Array<{ info: FunctionInfo; reason: string }> = [];

    for (const info of input.functions) {
      const taskId = functionTaskId(info.address);
      const result = input.functionResults.get(taskId);
      if (!result) {
        unreconstructed.push({ info, reason: 'not attempted' });
        continue;
      }
      if (result.status === 'unreconstructable') {
        unreconstructed.push({
          info,
          reason: result.reason ?? 'marked unreconstructable by the agent',
        });
        continue;
      }
      const base = sanitizeIdentifier(result.name);
      const file = usedNames.has(base) ? `src/${base}_${info.address.slice(2)}.c` : `src/${base}.c`;
      usedNames.set(base, taskId);
      reconstructed.push({ info, result, file });
    }

    await emit('include/recode_types.h', renderTypesHeader(input.typesResult?.header), 'types');

    const headerLines: string[] = [
      '/* Generated by ReCode. Prototypes of all analyzed functions. */',
      '#ifndef RECODE_FUNCTIONS_H',
      '#define RECODE_FUNCTIONS_H',
      '',
      '#include "recode_types.h"',
      '',
    ];
    for (const { info, result } of reconstructed) {
      headerLines.push(`/* 0x${info.address.slice(2)} (${result.confidence}) */`);
      headerLines.push(terminated(result.prototype));
      fileMap.headerLines[String(headerLines.length)] = functionTaskId(info.address);
    }
    for (const { info, reason } of unreconstructed) {
      headerLines.push(
        `/* NOT RECONSTRUCTED ${info.address} ${commentSafe(info.name)}: ${commentSafe(reason)} -- Ghidra: ${commentSafe(info.signature)} */`,
      );
    }
    // Callers reconstructed before their callee (relaxed scheduling) still use the decompiler's default name.
    const aliases = reconstructed.filter(
      ({ info, result }) =>
        info.name !== result.name &&
        /^(FUN|thunk_FUN)_[0-9a-fA-F]+$/.test(info.name) &&
        !reconstructed.some((other) => other.result.name === info.name),
    );
    if (aliases.length > 0) {
      headerLines.push('', '/* Decompiler default names of reconstructed functions. */');
      for (const { info, result } of aliases)
        headerLines.push(`#define ${info.name} ${result.name}`);
    }
    headerLines.push('', '#endif /* RECODE_FUNCTIONS_H */', '');
    await emit('include/recode_functions.h', headerLines.join('\n'));

    for (const { info, result, file } of reconstructed) {
      await emit(file, renderFunctionFile(info, result), functionTaskId(info.address));
    }

    await emit(
      'CMakeLists.txt',
      await renderCMake(
        binary.id,
        reconstructed.map((r) => r.file),
        reconstructed.some((r) => r.result.name === 'main'),
      ),
    );
    await emit('RECONSTRUCTION.md', renderReport(binary.fileName, reconstructed, unreconstructed));

    // Remove files from the previous generation that are no longer produced (never user files).
    for (const stale of previous?.files ?? []) {
      if (!written.has(stale) && (await pathExists(path.join(root, stale)))) {
        await fs.rm(path.join(root, stale), { force: true });
      }
    }
    await writeJsonAtomic(path.join(root, GENERATED_MANIFEST), { files: [...written], fileMap });

    return {
      directory: root,
      fileMap,
      reconstructed: reconstructed.length,
      unreconstructed: unreconstructed.filter((u) => u.reason !== 'not attempted').length,
      notAttempted: unreconstructed.filter((u) => u.reason === 'not attempted').length,
    };
  }
}

const TYPES_GUARD = 'RECODE_TYPES_H';

/** The generated shared-types header (used by the project generator and by the per-function compile check). */
export function renderTypesHeader(typesHeader: string | undefined): string {
  return [
    '/* Generated by ReCode from the structure analysis. Do not edit by hand. */',
    `#ifndef ${TYPES_GUARD}`,
    `#define ${TYPES_GUARD}`,
    '',
    '#include <stddef.h>',
    '#include <stdint.h>',
    '#include <stdbool.h>',
    '',
    typesHeader?.trim() ?? '/* No shared types were reconstructed. */',
    '',
    `#endif /* ${TYPES_GUARD} */`,
    '',
  ].join('\n');
}

export function renderFunctionFile(info: FunctionInfo, result: FunctionResult): string {
  const includes = [...new Set(['stdint.h', 'stddef.h', 'stdbool.h', ...result.includes])];
  const assumptions = result.assumptions.length
    ? result.assumptions.map((a) => ` *   - [${a.confidence}] ${commentSafe(a.text)}`)
    : [' *   (none recorded)'];
  return [
    '/*',
    ` * ReCode reconstruction of ${commentSafe(info.name)} @ ${info.address} (${info.size} bytes)`,
    ` * Reconstructed name: ${result.name}`,
    ` * Overall confidence: ${result.confidence}`,
    ' * Assumptions:',
    ...assumptions,
    ' */',
    ...includes.map((h) => `#include <${h}>`),
    '#include "recode_types.h"',
    '#include "recode_functions.h"',
    '',
    result.code.trim(),
    '',
  ].join('\n');
}

async function renderCMake(binaryId: string, sources: string[], hasMain: boolean): Promise<string> {
  const template = await fs.readFile(path.join(templateDirectory(), 'CMakeLists.txt.tmpl'), 'utf8');
  const projectName = sanitizeIdentifier(`recode_${binaryId}`);
  const sourceList =
    sources.length > 0
      ? sources.map((s) => `    ${s}`).join('\n')
      : '    # (no reconstructed functions yet)';
  return template
    .replaceAll('{{PROJECT_NAME}}', projectName)
    .replaceAll('{{SOURCES}}', sourceList)
    .replaceAll('{{HAS_MAIN}}', hasMain ? 'ON' : 'OFF');
}

function renderReport(
  fileName: string,
  reconstructed: Array<{ info: FunctionInfo; result: FunctionResult; file: string }>,
  unreconstructed: Array<{ info: FunctionInfo; reason: string }>,
): string {
  const rows = reconstructed.map(
    ({ info, result, file }) =>
      `| ${info.address} | ${info.name} | ${result.name} | ${result.confidence} | ${result.assumptions.length} | ${file} |`,
  );
  const missing = unreconstructed.map(
    ({ info, reason }) => `- ${info.address} \`${info.name}\`: ${reason}`,
  );
  return [
    `# Reconstruction of ${fileName}`,
    '',
    'Generated by ReCode. The source is an AI-assisted reconstruction, not the original code.',
    'Confidence levels: **certain** (directly evident), **probable** (inferred), **speculative** (guess).',
    '',
    '| Address | Original name | Reconstructed name | Confidence | Assumptions | File |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Not reconstructed',
    '',
    ...(missing.length > 0 ? missing : ['(none)']),
    '',
  ].join('\n');
}
